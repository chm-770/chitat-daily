function isYiddish(text: string): boolean {
  const yWords = ['איז', 'דער', 'דאס', 'דעם', 'ניט', 'נישט', 'אויף', 'מיט', 'וואס', 'געווען', 'האט', 'מען', 'וועגען', 'פאר', 'אזוי', 'זיי', 'איהם', 'ווייל', 'קיין', 'זיין', 'געזאגט', 'האבען', 'צוליב', 'ווען', 'בריינגט'];
  const words = text.split(/\s+/);
  let c = 0;
  for (const w of words) if (yWords.includes(w)) c++;
  return c >= 2;
}

let cleanedTransCount = 0;

for (const [k, v] of Object.entries(db as Record<string, any>)) {
  const text = v.text || [];
  const transIdx = text.findIndex((t: string) => t.trim() === 'תרגום לעברית:' || t.trim() === 'תרגום לעברית');
  if (transIdx !== -1) {
    const before = text.slice(0, transIdx).join(' ').trim();
    const after = text.slice(transIdx + 1).join(' ').trim();
    // If identical or after is Yiddish and not 18_6 or 25_10
    if (k !== '18_6' && k !== '25_10' && k !== '29_6') {
      if (before === after || isYiddish(after) || !after) {
        v.text = text.slice(0, transIdx);
        cleanedTransCount++;
      }
    }
  }
}

