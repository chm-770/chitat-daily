const MONTH_NAMES: Record<number, string> = {
  1: 'ניסן', 2: 'אייר', 3: 'סיוון', 4: 'תמוז', 5: 'מנחם אב', 6: 'אלול',
  7: 'תשרי', 8: 'מרחשוון', 9: 'כסלו', 10: 'טבת', 11: 'שבט', 12: 'אדר ראשון', 13: 'אדר שני'
};

const fullSchedule: Record<string, DailyMitzvahEntry> = {};

for (const [monthStr, daysObj] of Object.entries(RAW_SCHEDULE)) {
  const monthNum = parseInt(monthStr, 10);
  const monthName = MONTH_NAMES[monthNum] || `חודש ${monthNum}`;

  for (const [dayStr, displayStr] of Object.entries(daysObj)) {
    const dayNum = parseInt(dayStr, 10);
    const key = `${dayNum}_${monthNum}`;

    // Parse individual codes
    const parts = displayStr.split(/[\.,\s]+/).filter(Boolean);
    const mitzvotCodes: DailyMitzvahEntry['mitzvotCodes'] = [];

    let currentMode: 'aseh' | 'lotaseh' | 'intro' = 'aseh';
    for (const part of parts) {
      if (part.includes('עשה') || part === 'מ"ע' || part === 'מע') {
        currentMode = 'aseh';
      } else if (part.includes('תעשה') || part === 'מל"ת' || part === 'מלת') {
        currentMode = 'lotaseh';
      } else if (part.includes('שרש') || part.includes('הקדמ')) {
        currentMode = 'intro';
        mitzvotCodes.push({ type: 'intro', codeStr: part });
      } else {
        const num = parseHebrewNumber(part);
        if (num > 0) {
          mitzvotCodes.push({
            type: currentMode,
            number: num,
            codeStr: `${currentMode === 'aseh' ? 'מ"ע' : 'מל"ת'} ${part}`
          });
        }
      }
    }

    fullSchedule[key] = {
      dayNumber: dayNum,
      monthNumber: monthNum,
      monthName,
      hebrewDate: `${dayNum} ${monthName}`,
      mitzvotDisplay: displayStr,
      mitzvotCodes
    };
  }
}

const outPath = path.resolve('src/data/seferHaMitzvotDailySchedule.json');
fs.writeFileSync(outPath, JSON.stringify(fullSchedule, null, 2), 'utf-8');
console.log('Successfully generated Sefer HaMitzvot daily schedule:', Object.keys(fullSchedule).length, 'days');
